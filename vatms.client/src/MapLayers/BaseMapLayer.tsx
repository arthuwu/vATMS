import { useRef, useEffect } from 'react'
import { getProjection } from './mappingUtils';
import './maps.css'

interface MapProps {
    map: GeoJSON.FeatureCollection | null;  // TODO: remove null
    projectionCenter: [lat: number, long: number];
    zoom: number;
}

const BaseMapLayer = ({ projectionCenter, zoom }: MapProps) => {
    const canvasRef = useRef<HTMLCanvasElement>(null);

    const DrawMap = async () => { // TODO: this is testing code that was generated by an LLM. REMOVE.
        const canvas = canvasRef.current;
        if (!canvas) return;

        const ctx = canvas.getContext("2d");
        if (!ctx) return;

        const width = canvas.clientWidth;
        const height = canvas.clientHeight;

        canvas.width = width;
        canvas.height = height;

        // center canvas
        ctx.translate(width / 2, height / 2);

        const response = await fetch("https://raw.githubusercontent.com/holtzy/D3-graph-gallery/master/DATA/world.geojson");
        const geojson = await response.json();

        for (const feature of geojson.features) {
            const geometry = feature.geometry;

            let polygons: number[][][] = [];

            if (geometry.type === "Polygon") {
                polygons = geometry.coordinates;
            } else if (geometry.type === "MultiPolygon") {
                geometry.coordinates.forEach((poly: number[][][]) => {
                    polygons.push(...poly);
                });
            }

            for (const ring of polygons) {
                const points: [number, number][] = [];

                for (const coord of ring) {
                    let [x, y] = getProjection([coord[1], coord[0]], projectionCenter, zoom)
                    //[x, y] = rotateProjection90Clockwise(x, y);

                    points.push([x, y]);
                }

                if (points.length > 1) {
                    ctx.beginPath();
                    const [startX, startY] = points[0];
                    ctx.moveTo(startX, startY);

                    for (let i = 1; i < points.length; i++) {
                        const [x, y] = points[i];
                        ctx.lineTo(x, y);
                    }

                    ctx.closePath();
                    ctx.strokeStyle = "#000";
                    ctx.lineWidth = 1;
                    ctx.stroke();
                }
            }
        }

        // let [x, y, z] = convertDDToCartesian(projectionCenter[0], projectionCenter[1]);
        // [x, y, z] = rotateCartesianByCenter(projectionCenter[0], projectionCenter[1], [x, y, z]);
        // [x, y] = stereographicProjection(x, y, z);
        // [x, y] = applyZoomToProjected(x, y, zoom);

        let [x_c, y_c] = getProjection(projectionCenter, projectionCenter, zoom)

        const radius = 4;

        ctx.beginPath();
        ctx.arc(x_c, y_c, radius, 0, Math.PI * 2);
        ctx.fillStyle = "red";
        ctx.fill();
    };

    useEffect(() => {
        DrawMap();

        const handleResize = () => {
            DrawMap();
        }

        window.addEventListener('resize', handleResize);

        return () => {
            window.removeEventListener('resize', handleResize);
        };
    }, [projectionCenter, zoom]);


    return <canvas className="base-map-layer" ref={canvasRef} />
}

export default BaseMapLayer;