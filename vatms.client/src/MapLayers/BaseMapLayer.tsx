import { useRef, useEffect } from 'react'
import { getProjection } from './mappingUtils';
import type { MapPropsInterface } from './MapInterface';
import './maps.css'
// TODO: temp

interface MapProps extends MapPropsInterface {
    map: GeoJSON.FeatureCollection | null;  // TODO: remove null
}

const BaseMapLayer = ({ projectionCenter, zoom, screenSize }: MapProps) => {
    const canvasRef = useRef<HTMLCanvasElement>(null);

    const DrawMap = async () => { // TODO: this is testing code that was generated by an LLM. REMOVE.
        const canvas = canvasRef.current;
        if (!canvas) return;

        const ctx = canvas.getContext("2d");
        if (!ctx) return;

        canvas.width = screenSize[0];
        canvas.height = screenSize[1];

        // center canvas
        ctx.translate(canvas.width / 2, canvas.height / 2);

        const response = await fetch("https://raw.githubusercontent.com/holtzy/D3-graph-gallery/master/DATA/world.geojson");
        const geojson = await response.json();

        for (const feature of geojson.features) {
            const geometry = feature.geometry;

            let polygons: number[][][] = [];

            if (geometry.type === "Polygon") {
                polygons = geometry.coordinates;
            } else if (geometry.type === "MultiPolygon") {
                geometry.coordinates.forEach((poly: number[][][]) => {
                    polygons.push(...poly);
                });
            }

            for (const ring of polygons) {
                const points: [number, number][] = [];

                for (const coord of ring) {
                    let [x, y] = getProjection([coord[1], coord[0]], projectionCenter, zoom)
                    //[x, y] = rotateProjection90Clockwise(x, y);

                    points.push([x, y]);
                }

                if (points.length > 1) {
                    ctx.beginPath();
                    const [startX, startY] = points[0];
                    ctx.moveTo(startX, startY);

                    for (let i = 1; i < points.length; i++) {
                        const [x, y] = points[i];
                        ctx.lineTo(x, y);
                    }

                    ctx.closePath();
                    ctx.strokeStyle = "#000";
                    ctx.lineWidth = 1;
                    ctx.stroke();
                }
            }
        }
    };

    useEffect(() => {
        DrawMap();

        const handleResize = () => {
            DrawMap();
        }

        window.addEventListener('resize', handleResize);

        return () => {
            window.removeEventListener('resize', handleResize);
        };
    }, [projectionCenter, zoom, screenSize]);


    return <canvas className="base-map-layer" ref={canvasRef} />
}

export default BaseMapLayer;